/**
 * The marked friction-trigger block reader (ADR 0024 §2, spec-friction-capture-020
 * §The trigger and its visibility).
 *
 * The trigger is a rule agents must re-learn, so it is carried in the GENERATED
 * agent files — not only in a skill reference. `deftai/directive#3633` shipped a
 * sanctioned escalation skill and an agent that was actively escalating still
 * missed it: the friction was "absorbed into the session", which is silent loss
 * and looks like success. A capability in the wrong place is absent.
 *
 * Two readers over one marker, because two different questions are asked of the
 * same block:
 *
 *  - `carriesFrictionTrigger(templateText)` — does this TEMPLATE ship the block?
 *    That is the carrier set, and it is why a new seam joins `doctor`'s friction
 *    report with no code change: drop the block in the template and the report
 *    picks it up.
 *  - `readFrictionTrigger(fileBytes)` — does this GENERATED FILE carry it, and at
 *    which `triggerVersion`? That is what the compliance spike observes, and the
 *    version is what separates "present at 0.10.0" from "present at 0.11.0" — the
 *    one distinction a single boolean against a template that also moves for
 *    unrelated reasons cannot make.
 *
 * The version is rendered at write time from the `<arggonVersion>` placeholder in
 * the template (`renderDocPlaceholders`, cli/src/docs.ts), so a file generated by
 * an older arggon keeps that older version and the block reports it honestly
 * rather than claiming the running build's.
 */

/**
 * `<!-- arggon:friction-trigger begin triggerVersion=<arggonVersion> -->`. The
 * attribute tail is captured lazily so a value carrying its own `>` (the
 * `<arggonVersion>` placeholder does) still reaches the closing `-->`; `\b` after
 * `begin` keeps it from matching a longer hypothetical word.
 */
const TRIGGER_BEGIN = /<!--\s*arggon:friction-trigger begin\b([\s\S]*?)-->/;

/** The `triggerVersion=<value>` attribute inside the begin marker's tail. */
const TRIGGER_VERSION = /triggerVersion\s*=\s*"?([^"\s]+?)"?\s*$/;

/*
 * NOTE: the unresolved placeholder token itself is deliberately NOT a literal in
 * this module. This source is inlined into the plugin bundle
 * (`opencode/plugins/arggon/index.bundle.ts`), and that bundle is rendered by
 * `renderDocPlaceholders` when init vendors it — so a literal token here would be
 * rewritten inside the bundle and every vendored copy would report drifted. The
 * token is a TEMPLATE concern: it lives in
 * `templates/docs/opencode/agents/*.md` and the CLI's render resolves it. The
 * reader below never needs to know it.
 */

/** Does this text ship the marked friction-trigger block at all? */
export function carriesFrictionTrigger(content: string): boolean {
  return TRIGGER_BEGIN.test(content);
}
/**
 * The trigger state of one file: whether the marked block is there, and the
 * `triggerVersion` it carries (`null` when the block is absent — reported, never
 * guessed, so "never seen" stays distinguishable from "seen and ignored").
 *
 * A template's own `triggerVersion=<arggonVersion>` reads as the literal
 * placeholder: it has no version yet because the render is what gives it one.
 * Reporting it verbatim keeps a template read honest about being a source, not a
 * generated file.
 */
export function readFrictionTrigger(content: string): {
  present: boolean;
  triggerVersion: string | null;
} {
  const begin = TRIGGER_BEGIN.exec(content);
  if (begin === null) return { present: false, triggerVersion: null };
  const version = TRIGGER_VERSION.exec(begin[1] ?? "")?.[1] ?? null;
  return { present: true, triggerVersion: version };
}

/**
 * The destination path of a managed AGENT file — the population `doctor`'s
 * friction block reports (ADR 0024 §2: "per managed agent file"). A Markdown file
 * under an `agents/` directory is an agent file in every seam arggon materializes
 * (`.opencode/agents/`, `.claude-marketplace/arggon/agents/`,
 * `.zcode-marketplace/arggon/agents/`), and a carrier in any other kind of file
 * would not be a file an agent loads as its contract.
 */
export function isManagedAgentDest(dest: string): boolean {
  return dest.endsWith(".md") && /(^|\/)agents\//.test(dest);
}

#!/usr/bin/env node
/**
 * Shared hermetic-serving helpers for the OpenCode plugin smokes
 * (`smoke/opencode-smoke.ts`, `smoke/native-start-cold-smoke.ts`'s move leg,
 * and the pattern the model-free T4 smokes already follow).
 *
 * Why a hermetic HOME
 * -------------------
 * The OpenCode plugin supervisor resolves plugins from the machine-global
 * config home (`$XDG_CONFIG_HOME/opencode/plugins`, i.e.
 * `~/.config/opencode/plugins` on this box) and reconciles them by plugin id:
 * a machine-global `plugins/arggon` copy therefore competes with the fixture's
 * vendored bundle for the same id, and a fixture run that inherits the host
 * environment may exercise the global copy instead of THIS checkout's plugin —
 * its evidence would prove nothing about this checkout. Serving with `HOME`
 * and every `XDG_*` under a disposable directory removes the whole global
 * surface (plugins, config, MCP servers, global `AGENTS.md`) in one move.
 *
 * Model-driven runs additionally need the host's provider credentials. On V2
 * they live in the SQLite store under the data home (the models-dev catalog
 * too), not in `auth.json`; probes on 2.0.26: a fresh home plus a copied
 * `auth.json` answers `Model unavailable`, while `opencode auth export` →
 * `opencode auth import --standalone` into the hermetic home resolves the
 * provider. {@link seedHermeticCredentials} is that supported seam; model-free
 * legs (scripted providers) don't need it.
 *
 * The isolation is asserted, not assumed: {@link pluginEvidenceFaults} reads
 * the host log's own `loading plugin id=…` line and requires the fixture's
 * plugin directory to be the one named — a machine-global copy would be named
 * instead (or alongside), which fails the check loudly.
 */
import { spawnSync } from "node:child_process";
import { chmodSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * The provenance line `arggon init` prepends to a vendored copy. A fixture that
 * copies the committed bundle itself has no marker; one generated by `init`
 * does — the bytes after it must equal the committed bundle exactly either way.
 */
export const GENERATED_MARKER_PREFIX = "// arggon:generated";

/** A vendored copy's bytes with the optional `// arggon:generated` line removed. */
export function vendoredSource(vendored: string): string {
  return vendored.startsWith(GENERATED_MARKER_PREFIX)
    ? vendored.slice(vendored.indexOf("\n") + 1)
    : vendored;
}

/** True when a vendored copy is exactly the committed source, the marker line aside. */
export function vendoredSourceMatches(vendored: string, source: string): boolean {
  return vendoredSource(vendored) === source;
}

/** The host's own config home: where a machine-global plugin would be discovered. */
export function hostConfigHome(env: NodeJS.ProcessEnv = process.env): string {
  return env.XDG_CONFIG_HOME ?? join(env.HOME ?? "", ".config");
}

export type HermeticHome = {
  /** The disposable directory holding HOME and every XDG_* below it. */
  root: string;
  /**
   * `HOME` plus the four XDG dirs OpenCode reads, all under {@link root}.
   * `XDG_DATA_HOME`/`XDG_STATE_HOME`/`XDG_CACHE_HOME` are here for the same
   * reason as `HOME`: session state must not leak into (or out of) the host's
   * store — a model-driven run seeds what it needs into this store instead.
   */
  env: {
    HOME: string;
    XDG_CONFIG_HOME: string;
    XDG_DATA_HOME: string;
    XDG_STATE_HOME: string;
    XDG_CACHE_HOME: string;
  };
};

/**
 * Create a disposable HOME + XDG set under `parent/<name>`. Nothing is seeded:
 * a model-free leg is ready to serve, a model-driven one calls
 * {@link seedHermeticCredentials} first.
 */
export function createHermeticHome(parent: string, name = "home"): HermeticHome {
  const root = join(parent, name);
  const env = {
    HOME: root,
    XDG_CONFIG_HOME: join(root, ".config"),
    XDG_DATA_HOME: join(root, ".local", "share"),
    XDG_STATE_HOME: join(root, ".local", "state"),
    XDG_CACHE_HOME: join(root, ".cache"),
  };
  for (const dir of Object.values(env)) mkdirSync(dir, { recursive: true });
  return { root, env };
}

/**
 * Faults in one host log's plugin evidence (empty = the fixture's own plugin
 * was the one named as loaded, and no machine-global plugin directory was
 * discovered). `log` is a `serve` log or a `run --print-logs` stderr.
 *
 * The `loading plugin id=<dir>` line is the supervisor's own statement of which
 * plugin it loaded; asserting it against the fixture's absolute path(s) is the
 * one check that cannot pass by accident. `pluginDirs` is any-of because a
 * session moved into a worktree still loads the plugin from the project's
 * canonical checkout (observed on 2.0.26) — both copies are fixture copies.
 */
export function pluginEvidenceFaults(
  log: string,
  expected: { pluginDirs: readonly string[]; hostConfigHome: string },
): string[] {
  const faults: string[] = [];
  const observed = [
    ...new Set(
      log
        .split("\n")
        .filter((line) => line.includes("loading plugin"))
        .map((line) => /id=([^\s]+)/.exec(line)?.[1] ?? line.trim())
        .filter((value) => value !== ""),
    ),
  ];
  if (!observed.some((dir) => expected.pluginDirs.includes(dir))) {
    faults.push(
      `the host log never names a fixture plugin (${expected.pluginDirs.join(", ")}) as loaded; observed: ${
        observed.length === 0 ? "no loading-plugin line" : observed.slice(0, 5).join(", ")
      }`,
    );
  }
  const globalPlugins = join(expected.hostConfigHome, "opencode", "plugins");
  if (log.includes(globalPlugins)) {
    faults.push(
      `the host log names the machine-global plugin directory ${globalPlugins} — the fixture bundle is not the only copy in play`,
    );
  }
  return faults;
}

export type CredentialSeed = {
  ok: boolean;
  /** Credentials imported into the hermetic store (0 = nothing imported). */
  credentials?: number;
  error?: string;
};

/**
 * Seed a hermetic home with the host's provider credentials so a real
 * model-driven session can resolve its provider from the hermetic store.
 *
 * Uses the CLI's own supported seam: `opencode auth export` under the host
 * environment, then `opencode auth import --standalone <file>` under the
 * hermetic one. `providers` filters the export to the integrations a run
 * actually needs, so the host's whole credential set is never written to disk;
 * the exported file is deleted as soon as the import returns.
 *
 * The call is bounded and its failure is returned, never thrown: the caller
 * decides whether a missing credential is a failed run (it is — a model-driven
 * smoke cannot serve without a provider) or out of scope.
 */
export function seedHermeticCredentials(
  bin: string,
  home: HermeticHome,
  options: { providers?: readonly string[]; hostEnv?: NodeJS.ProcessEnv; timeoutMs?: number } = {},
): CredentialSeed {
  const timeout = options.timeoutMs ?? 120_000;
  const hostEnv = options.hostEnv ?? process.env;
  const exported = spawnSync(bin, ["auth", "export"], {
    env: hostEnv,
    encoding: "utf8",
    timeout,
    maxBuffer: 16 * 1024 * 1024,
  });
  if (exported.error !== undefined || exported.status !== 0) {
    return {
      ok: false,
      error: `opencode auth export failed in the host environment: ${
        (exported.error?.message ?? (exported.stderr ?? "").trim()) ||
        `exit ${String(exported.status)}`
      }`,
    };
  }
  let entries: Array<Record<string, unknown>>;
  try {
    const parsed = JSON.parse(exported.stdout ?? "") as unknown;
    entries = Array.isArray(parsed) ? (parsed as Array<Record<string, unknown>>) : [];
  } catch {
    entries = [];
  }
  const wanted =
    options.providers === undefined
      ? entries
      : entries.filter((entry) => options.providers?.includes(String(entry.integrationID)));
  if (wanted.length === 0) {
    return {
      ok: false,
      error:
        options.providers === undefined
          ? "the host exported no credentials"
          : `the host has no credential for ${options.providers.join(", ")}`,
    };
  }
  // 0600: the file is short-lived but carries secrets.
  const file = join(home.root, "credential-seed.json");
  writeFileSync(file, JSON.stringify(wanted), { encoding: "utf8", mode: 0o600 });
  chmodSync(file, 0o600);
  try {
    const imported = spawnSync(bin, ["auth", "import", "--standalone", file], {
      env: { ...hostEnv, ...home.env },
      encoding: "utf8",
      timeout,
      maxBuffer: 16 * 1024 * 1024,
    });
    if (imported.error !== undefined || imported.status !== 0) {
      return {
        ok: false,
        error: `opencode auth import failed in the hermetic home: ${
          (imported.error?.message ?? (imported.stderr ?? "").trim()) ||
          `exit ${String(imported.status)}`
        }`,
      };
    }
    // The receipt is on stderr and singular/plural by count ("Imported 1
    // credential" / "Imported 4 credentials" — observed on 2.0.26).
    const count = Number(
      /Imported (\d+) credentials?/.exec(`${imported.stdout ?? ""}${imported.stderr ?? ""}`)?.[1] ??
        0,
    );
    if (!Number.isInteger(count) || count <= 0) {
      return {
        ok: false,
        error: `opencode auth import reported no credentials: ${`${imported.stdout ?? ""}${imported.stderr ?? ""}`.trim()}`,
      };
    }
    return { ok: true, credentials: count };
  } finally {
    // The secrets never outlive the import, including on failure.
    try {
      rmSync(file, { force: true });
    } catch {
      // Best effort: the whole home is disposable and removed by the caller.
    }
  }
}

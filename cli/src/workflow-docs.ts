import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * One canonical agent workflow, generated into its entrypoints (issue #869).
 *
 * The normative claim/completion contract lives in `ArggonManager/docs/agents.md`
 * §2 inside the `workflow-source` markers. Every copy-paste surface is either
 * generated from that region (the `arggon instructions` snippet, the adopter
 * AGENTS/CONTRIBUTING/copilot templates and this repository's generated
 * copilot instructions) or links to the published anchor. There is no second
 * recipe to drift.
 *
 * `npm run workflow:check` is check-only: CI must DETECT a stale copy, never
 * silently repair it. `npm run workflow:sync` renders the copies locally. The
 * full excerpt is emitted only where the whole contract is needed (the
 * copy-paste snippet); the adopter routers carry the generated pointer because
 * the generated `AGENTS.md` has a hard 2 KiB context budget
 * (`cli/src/init-docs.test.ts`).
 */

export const WORKFLOW_SOURCE = "ArggonManager/docs/agents.md";
export const WORKFLOW_ANCHOR = "canonical-workflow-contract";
export const WORKFLOW_URL = `https://github.com/Arggon/ArggonManager/blob/main/${WORKFLOW_SOURCE}#${WORKFLOW_ANCHOR}`;

/**
 * Destinations, in document order. `excerpt: true` renders the whole canonical
 * contract; `excerpt: false` renders the generated pointer. Every rendered
 * region carries the provenance line and the published contract URL.
 */
export const WORKFLOW_TARGETS = [
  // The doc region is a pointer: `arggon instructions` appends the canonical
  // contract at print time, so the start page pays no duplicate bytes.
  { path: WORKFLOW_SOURCE, excerpt: false },
  { path: "templates/docs/AGENTS.md", excerpt: false },
  { path: "templates/docs/CONTRIBUTING.md", excerpt: false },
  { path: "templates/docs/github/copilot-instructions.md", excerpt: false },
  // This repository's own generated copilot copy: the destination `init`
  // writes from the template above. It is adopter-editable in an adopting
  // tree; in the source checkout the drift gate keeps it on the template.
  { path: ".github/copilot-instructions.md", excerpt: false },
] as const;

const PROVENANCE = `<!-- Generated by npm run workflow:sync; edit ${WORKFLOW_SOURCE} instead. -->`;
const POINTER = `Follow the [canonical workflow contract](${WORKFLOW_URL}) for claiming and completing work.`;

export type WorkflowRegion = { start: number; end: number; body: string };

/**
 * Locate one ordered, line-delimited marker pair. Malformed markers must throw
 * rather than match a greedy slice: a bad edit to a target must not let the
 * sync erase the prose around it (the same invariant as the methodology
 * excerpts, but with a larger blast radius because these are entrypoints).
 */
export function workflowRegion(text: string, kind: "source" | "copy"): WorkflowRegion {
  const begin = `<!-- arggon:workflow-${kind}:start -->`;
  const end = `<!-- arggon:workflow-${kind}:end -->`;
  if (text.split(begin).length !== 2 || text.split(end).length !== 2) {
    throw new Error(`expected exactly one workflow-${kind} marker pair`);
  }
  const start = text.indexOf(begin);
  const finish = text.indexOf(end);
  if (
    finish <= start ||
    (start > 0 && text[start - 1] !== "\n") ||
    text[start + begin.length] !== "\n" ||
    text[finish - 1] !== "\n" ||
    (finish + end.length < text.length && text[finish + end.length] !== "\n")
  ) {
    throw new Error(`malformed workflow-${kind} marker boundaries`);
  }
  return {
    start: start + begin.length + 1,
    end: finish,
    body: text.slice(start + begin.length + 1, finish),
  };
}

/** The canonical contract region, with the anchor the published URL targets. */
export function canonicalContract(source: string): string {
  if (!source.includes(`id="${WORKFLOW_ANCHOR}"`)) {
    throw new Error(
      `${WORKFLOW_SOURCE} does not publish the '#${WORKFLOW_ANCHOR}' anchor the copies link to`,
    );
  }
  const contract = workflowRegion(source, "source").body;
  if (!contract.trim()) throw new Error("canonical workflow contract is empty");
  return contract;
}

/** Render one target's copy region from the canonical contract. */
export function renderWorkflowCopy(target: string, source: string, excerpt: boolean): string {
  const contract = canonicalContract(source);
  const region = workflowRegion(target, "copy");
  const body = `${PROVENANCE}\n\n${POINTER}\n${excerpt ? `\n${contract}` : ""}`;
  return target.slice(0, region.start) + body + target.slice(region.end);
}

/**
 * Plan every destination before writing any: one malformed target must fail
 * the run with every file untouched. Returns the paths that differ (or were
 * rewritten with `write: true`).
 */
export function syncWorkflowDocs(root: string, write = false): string[] {
  const source = readFileSync(join(root, WORKFLOW_SOURCE), "utf8");
  const changes = WORKFLOW_TARGETS.map(({ path, excerpt }) => {
    const current = readFileSync(join(root, path), "utf8");
    return { path, current, expected: renderWorkflowCopy(current, source, excerpt) };
  }).filter(({ current, expected }) => current !== expected);
  if (write) {
    for (const { path, expected } of changes) writeFileSync(join(root, path), expected);
  }
  return changes.map(({ path }) => path);
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
  const write = process.argv.includes("--write");
  try {
    const stale = syncWorkflowDocs(root, write);
    if (!write && stale.length > 0) {
      console.error(
        `Workflow docs drifted: ${stale.join(", ")}. Run npm run workflow:sync, then npm run skills:sync.`,
      );
      process.exitCode = 1;
    } else {
      console.log(
        write ? `Synced ${stale.length} workflow document(s).` : "Workflow docs are current.",
      );
    }
  } catch (error) {
    console.error(`Workflow docs: ${(error as Error).message}`);
    process.exitCode = 1;
  }
}

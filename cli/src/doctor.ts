function isJsonObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/**
 * Tolerant JSONC parse (task-opencode-v2-doctor): OpenCode configs may be
 * `opencode.jsonc` with `//`/`/* *\/` comments and trailing commas, which
 * `JSON.parse` rejects. Comments outside strings are stripped and trailing
 * commas before `}`/`]` dropped by one linear string-aware scan each, then
 * `JSON.parse` runs; malformed input returns null — doctor never throws on
 * adopter content and never rewrites it.
 */
function parseJsonc(text: string): unknown | null {
  let stripped = "";
  let inString = false;
  let escaped = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i]!;
    if (inString) {
      stripped += ch;
      if (escaped) escaped = false;
      else if (ch === "\\") escaped = true;
      else if (ch === '"') inString = false;
      continue;
    }
    if (ch === '"') {
      inString = true;
      stripped += ch;
      continue;
    }
    if (ch === "/" && text[i + 1] === "/") {
      while (i < text.length && text[i] !== "\n") i++;
      stripped += "\n";
      continue;
    }
    if (ch === "/" && text[i + 1] === "*") {
      i += 2;
      while (i < text.length && !(text[i] === "*" && text[i + 1] === "/")) i++;
      i++; // land on the closing '/'; the outer loop steps past it
      continue;
    }
    stripped += ch;
  }
  let json = "";
  inString = false;
  escaped = false;
  for (let i = 0; i < stripped.length; i++) {
    const ch = stripped[i]!;
    if (inString) {
      json += ch;
      if (escaped) escaped = false;
      else if (ch === "\\") escaped = true;
      else if (ch === '"') inString = false;
      continue;
    }
    if (ch === '"') {
      inString = true;
      json += ch;
      continue;
    }
    if (ch === ",") {
      let j = i + 1;
      while (j < stripped.length && /\s/.test(stripped[j]!)) j++;
      if (stripped[j] === "}" || stripped[j] === "]") continue; // drop the trailing comma
    }
    json += ch;
  }
  try {
    return JSON.parse(json) as unknown;
  } catch {
    return null;
  }
}

/** Read + tolerant-parse a JSON(C) file; null when absent, unreadable, or malformed. */
function readJsonObject(absPath: string): Record<string, unknown> | null {
  let text: string;
  try {
    text = readFileSync(absPath, "utf8");
  } catch {
    return null;
  }
  const parsed = parseJsonc(text);
  return isJsonObject(parsed) ? parsed : null;
}

/** V1-shaped key hits in one parsed OpenCode config, sorted. */
function v1ShapedKeys(config: Record<string, unknown>): string[] {
  const keys: string[] = [];
  for (const key of OPENCODE_V1_KEYS) {
    if (Object.prototype.hasOwnProperty.call(config, key)) keys.push(key);
  }
  const mcp = config["mcp"];
  if (isJsonObject(mcp)) {
    for (const name of Object.keys(mcp)) {
      if (!OPENCODE_V2_MCP_KEYS.has(name)) keys.push(`mcp.${name}`);
    }
  }
  return keys.sort();
}

type NameList = { names: string[]; truncated: boolean };

/** Sorted `.md` stems in a fixed directory, capped. Never recurses, never throws. */
function listMarkdownNames(absDir: string): NameList {
  let entries: Dirent[];
  try {
    entries = readdirSync(absDir, { withFileTypes: true });
  } catch {
    return { names: [], truncated: false };
  }
  const names = entries
    .filter((entry) => entry.isFile() && entry.name.endsWith(".md"))
    .map((entry) => entry.name.slice(0, -".md".length))
    .sort();
  return {
    names: names.slice(0, MAX_OPENCODE_NAMES),
    truncated: names.length > MAX_OPENCODE_NAMES,
  };
}

/** Sorted directory names in a fixed directory, capped. Never recurses, never throws. */
function listDirNames(absDir: string): NameList {
  let entries: Dirent[];
  try {
    entries = readdirSync(absDir, { withFileTypes: true });
  } catch {
    return { names: [], truncated: false };
  }
  const names = entries
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  return {
    names: names.slice(0, MAX_OPENCODE_NAMES),
    truncated: names.length > MAX_OPENCODE_NAMES,
  };
}

/**
 * OpenCode integration probe (task-opencode-v2-doctor): pure read over fixed
 * paths — the four config candidates, `.mcp.json`, and one non-recursive
 * readdir each for `.opencode/agents`, `.opencode/commands`, `.agents/skills`.
 * Never throws, never writes; all lists are capped (MAX_OPENCODE_NAMES /
 * MAX_OPENCODE_V1_KEYS_PER_FILE).
 */
export function detectOpenCode(root: string): DoctorOpenCode {
  const configs: string[] = [];
  const findings: Array<{ file: string; keys: string[] }> = [];
  let v1Truncated = false;
  let native = false;
  for (const rel of OPENCODE_CONFIG_CANDIDATES) {
    const abs = join(root, ...rel.split("/"));
    if (!existsSync(abs)) continue;
    configs.push(rel);
    const parsed = readJsonObject(abs);
    if (parsed === null) continue; // present but unreadable/malformed
    const keys = v1ShapedKeys(parsed);
    if (keys.length > 0) {
      if (keys.length > MAX_OPENCODE_V1_KEYS_PER_FILE) {
        keys.length = MAX_OPENCODE_V1_KEYS_PER_FILE;
        v1Truncated = true;
      }
      findings.push({ file: rel, keys });
    }
    const mcp = parsed["mcp"];
    const servers = isJsonObject(mcp) ? mcp["servers"] : undefined;
    if (isJsonObject(servers) && Object.prototype.hasOwnProperty.call(servers, "arggon")) {
      native = true;
    }
  }

  const agents = listMarkdownNames(join(root, ".opencode", "agents"));
  const commands = listMarkdownNames(join(root, ".opencode", "commands"));
  const skills = listDirNames(join(root, ".agents", "skills"));
  const mcpJsonConfig = readJsonObject(join(root, ".mcp.json"));
  const mcpServers =
    mcpJsonConfig && isJsonObject(mcpJsonConfig["mcpServers"])
      ? mcpJsonConfig["mcpServers"]
      : undefined;
  const mcpJson =
    mcpServers !== undefined && Object.prototype.hasOwnProperty.call(mcpServers, "arggon");

  return {
    configs,
    v1: { findings, truncated: v1Truncated },
    artifacts: {
      config: existsSync(join(root, "opencode.jsonc")),
      agents: agents.names,
      commands: commands.names,
      skills: skills.names,
      truncated: agents.truncated || commands.truncated || skills.truncated,
    },
    plugin: readPluginFreshness(root),
    mcp: {
      native,
      mcpJson,
      // W3: the default seam writes no MCP stanza, so a present one is
      // reported as optional (removal guidance), never as a missing step.
      hint: native ? OPENCODE_MCP_HINT : null,
    },
  };
}

/**
 * Per-adapter-file state (`doctor --agents`, spec §S2,
 * task-adapter-selection-flags). Exactly one status per destination, decided
 * from what is already on disk plus the shipped templates — never a verdict and
 * never a gate. Every status names what `arggon init` would DO with the file,
 * because a status is only useful if it maps onto a real operator action: no
 * label may promise a protection or a refresh init does not provide.
 *
 * The vocabulary mirrors the `docs` block in this same payload
 * (`docs.acknowledged` / `docs.acknowledgedDrifted`), so one envelope never says
 * `present` for a file the other half calls acknowledged:
 *
 *  - `present` — on disk and byte-equal to the CURRENT template render: exactly
 *    what an untouched re-run would leave there.
 *  - `acknowledged` — on disk and byte-equal to the **acked baseline**
 *    (`arggon adopt --ack`, bug-ack-baseline-regen-loss): sanctioned content.
 *    `arggon adopt --ack` acks EVERY state entry, so this is the normal state of
 *    a fully-adopted tree, not an edge case. Init never regenerates it.
 *  - `acknowledged-drifted` — acknowledged, but the bytes have since diverged
 *    from the acked baseline (bug-ack-drift-promise): a hand edit landed AFTER
 *    the ack. Still adopter-owned and never regenerated; the edit is what the
 *    operator may want to re-ack (`arggon adopt --ack`) or revert.
 *  - `adopter-edited` — a hand edit landed on an ordinary generated file (the
 *    recorded checksum differs), or the file is on disk with **no provenance
 *    state at all** (docs.ts treats exactly that case as adopter-modified, since
 *    a pre-provenance file is not arggon's to rewrite). Init skips it by
 *    default; `--backup` archives it and regenerates.
 *  - `stale` — state-backed and untouched (the checksum matches), but the
 *    current template render differs: upstream moved and `arggon init` WOULD
 *    refresh it. Requires a state entry, because without one init refuses to
 *    touch the file — reporting `stale` there would send an operator to a
 *    command that cannot work.
 *  - `missing` — tracked by the seam but absent from the tree.
 *  - `unverified` — the render cannot be produced (template/bundle absent, or
 *    the project name is unrecoverable): "cannot decide", never a failure.
 *  - `orphaned` — an `x-generated` destination whose RECORDED template no longer
 *    exists in this arggon version (task-adapter-orphan-reaping,
 *    spec-agent-rename-019 §The precondition): init can neither refresh it nor
 *    keep generating it, yet the file is still on disk and — under an
 *    auto-discovered seam directory like `.opencode/agents/` — still
 *    DISPATCHABLE. The remedy is on the row itself (`reap`), because the answer
 *    is per file: `arggon init` removes it when it is still exactly as
 *    generated, and otherwise the adopter deletes it by hand (or restores the
 *    template). Nothing is reaped until `init` runs, and doctor is report-only.
 *
 * "The template moved on" is deliberately NOT one of these: it is orthogonal to
 * the local state and is already carried, for every one of these files, by
 * `docs.outdated` / `docs.outdatedDocs` in this same payload.
 */
export type AdapterFileStatus =
  | "present"
  | "acknowledged"
  | "acknowledged-drifted"
  | "adopter-edited"
  | "stale"
  | "missing"
  | "unverified"
  | "orphaned";

/** One adapter destination and its state. */
export type AdapterFileState = {
  /** Destination path (posix, relative to the probed root). */
  path: string;
  status: AdapterFileStatus;
  /**
   * Present ONLY on an `orphaned` row: what `arggon init` would DO with this
   * file, read from the same classifier init acts on (`planOrphanReaps`), so
   * the report cannot promise a deletion init would refuse (or refuse one it
   * would perform). `reap` = init removes it; `refuse` = init keeps it and
   * `reason` says why (an edit since the recorded baseline, a downgrade, a
   * non-regular file, outside the repo root, not on disk). An acknowledged
   * orphan is NOT a refusal — see `classifyOrphan` in `cli/src/docs.ts` for the
   * policy; its `reason` names the ack so the operator sees it before acting.
   */
  reap?: { action: "reap" | "refuse"; reason: string };
};

